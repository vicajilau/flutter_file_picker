import 'dart:async';

import 'package:file_picker_platform_interface/file_picker_platform_interface.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter/services.dart';

import 'android_platform_file.dart';
import 'file_picker_android_options.dart';
import 'lost_file_picker_result.dart';
import 'messages.g.dart';

/// An implementation of [FilePickerPlatform] for Android.
class FilePickerAndroid extends FilePickerPlatform {
  /// Creates the Android implementation. [api] replaces the generated Pigeon
  /// API in tests.
  FilePickerAndroid({@visibleForTesting FilePickerApi? api})
    : _api = api ?? FilePickerApi();

  /// Registers this class as the default instance of [FilePickerPlatform].
  static void registerWith() {
    FilePickerPlatform.instance = FilePickerAndroid();
  }

  /// The calls to the Android side, generated by Pigeon from
  /// `pigeons/messages.dart`.
  final FilePickerApi _api;

  /// The event channel used to receive real-time updates from the native platform.
  static const EventChannel _sharedEventChannel = EventChannel(
    'miguelruivo.flutter.plugins.filepickerevent',
  );

  // Share the messenger handler so overlapping calls cannot remove it.
  static final Stream<dynamic> _statusEvents = _sharedEventChannel
      .receiveBroadcastStream();

  @visibleForTesting
  final eventChannel = _sharedEventChannel;

  @override
  Future<PlatformFile?> pickFile({
    String? dialogTitle,
    String? initialDirectory,
    FileType type = FileType.any,
    List<String>? allowedExtensions,
    Function(FilePickerStatus)? onFileLoading,
    int compressionQuality = 0,
    AndroidOptions androidOptions = const FilePickerAndroidOptions(),
    DarwinOptions darwinOptions = const DarwinOptions(),
    WindowsOptions windowsOptions = const WindowsOptions(),
    LinuxOptions linuxOptions = const LinuxOptions(),
    WebOptions webOptions = const WebOptions(),
  }) async {
    final files = await _pickFilesInternal(
      allowMultiple: false,
      dialogTitle: dialogTitle,
      initialDirectory: initialDirectory,
      type: type,
      allowedExtensions: allowedExtensions,
      onFileLoading: onFileLoading,
      compressionQuality: compressionQuality,
      androidOptions: androidOptions,
    );
    return files.firstOrNull;
  }

  @override
  Future<List<PlatformFile>> pickFiles({
    String? dialogTitle,
    String? initialDirectory,
    FileType type = FileType.any,
    List<String>? allowedExtensions,
    Function(FilePickerStatus)? onFileLoading,
    int compressionQuality = 0,
    AndroidOptions androidOptions = const FilePickerAndroidOptions(),
    DarwinOptions darwinOptions = const DarwinOptions(),
    WindowsOptions windowsOptions = const WindowsOptions(),
    LinuxOptions linuxOptions = const LinuxOptions(),
    WebOptions webOptions = const WebOptions(),
  }) async {
    return _pickFilesInternal(
      allowMultiple: true,
      dialogTitle: dialogTitle,
      initialDirectory: initialDirectory,
      type: type,
      allowedExtensions: allowedExtensions,
      onFileLoading: onFileLoading,
      compressionQuality: compressionQuality,
      androidOptions: androidOptions,
    );
  }

  Future<List<PlatformFile>> _pickFilesInternal({
    required bool allowMultiple,
    String? dialogTitle,
    String? initialDirectory,
    FileType type = FileType.any,
    List<String>? allowedExtensions,
    Function(FilePickerStatus)? onFileLoading,
    int compressionQuality = 0,
    AndroidOptions androidOptions = const FilePickerAndroidOptions(),
  }) async {
    StreamSubscription<Object?>? eventSubscription;

    try {
      if (onFileLoading != null) {
        eventSubscription = _statusEvents.listen(
          (data) {
            if (data is! bool) return;
            onFileLoading(
              data ? FilePickerStatus.picking : FilePickerStatus.done,
            );
          },
          // A status update that fails is not worth failing the call over,
          // and throwing here only surfaced as an uncaught error.
          onError: (_) {},
        );
      }

      final result = await _api.pickFiles(
        _fileTypes[type]!,
        allowMultiple,
        allowedExtensions ?? const [],
        compressionQuality,
        _safOptions(androidOptions),
      );

      return [for (final file in result ?? const []) _platformFile(file)];
    } finally {
      await eventSubscription?.cancel();
      onFileLoading?.call(FilePickerStatus.done);
    }
  }

  @override
  Future<List<String>> pickFileAndDirectoryPaths({
    String? dialogTitle,
    String? initialDirectory,
    FileType type = FileType.any,
    List<String>? allowedExtensions,
  }) async {
    final files = await pickFiles(
      dialogTitle: dialogTitle,
      initialDirectory: initialDirectory,
      type: type,
      allowedExtensions: allowedExtensions,
    );
    return files.map((e) => e.path).nonNulls.toList();
  }

  @override
  Future<String?> getDirectoryPath({
    String? dialogTitle,
    String? initialDirectory,
    AndroidOptions androidOptions = const FilePickerAndroidOptions(),
    DarwinOptions darwinOptions = const DarwinOptions(),
    WindowsOptions windowsOptions = const WindowsOptions(),
    LinuxOptions linuxOptions = const LinuxOptions(),
    WebOptions webOptions = const WebOptions(),
  }) async {
    // A failure is thrown as a PlatformException, so the app can tell it
    // apart from a cancel, which completes with null (#2286).
    return _api.pickDirectory(_safOptions(androidOptions));
  }

  /// Recovers the files picked before Android destroyed the activity, or the
  /// whole app process, while the file picker was open, or `null` if there is
  /// nothing to recover.
  ///
  /// Only `pickFile()` and `pickFiles()` can be recovered. The outcome is
  /// delivered once, and only the most recent lost pick is kept. Call it
  /// early, for example in the `initState` of the screen that started the
  /// pick, which a `RestorationScope` can bring back:
  ///
  /// ```dart
  /// if (FilePickerPlatform.instance case final FilePickerAndroid android) {
  ///   final lost = await android.retrieveLostData();
  /// }
  /// ```
  Future<LostFilePickerResult?> retrieveLostData() async {
    final data = await _api.retrieveLostData();
    if (data == null) return null;

    if (data.errorCode case final code?) {
      return LostFilePickerResult(
        exception: PlatformException(code: code, message: data.errorMessage),
      );
    }

    return LostFilePickerResult(
      files: [for (final file in data.files ?? const []) _platformFile(file)],
    );
  }

  @override
  Future<void> clearTemporaryFiles() async {
    await _api.clearTemporaryFiles();
  }

  @override
  Future<Uri?> saveFile({
    required String fileName,
    required Uint8List bytes,
    required String mimeType,
    String? dialogTitle,
    String? initialDirectory,
    Function(FilePickerStatus)? onFileSaving,
    DarwinOptions darwinOptions = const DarwinOptions(),
    WindowsOptions windowsOptions = const WindowsOptions(),
    LinuxOptions linuxOptions = const LinuxOptions(),
    WebOptions webOptions = const WebOptions(),
  }) async {
    StreamSubscription<Object?>? eventSubscription;
    try {
      if (onFileSaving != null) {
        onFileSaving(FilePickerStatus.picking);
        eventSubscription = _statusEvents.listen(
          (data) {
            if (data is! bool) return;
            onFileSaving(
              data ? FilePickerStatus.picking : FilePickerStatus.done,
            );
          },
          // A status update that fails is not worth failing the call over,
          // and throwing here only surfaced as an uncaught error.
          onError: (_) {},
        );
      }

      final String? savedPath = await _api.saveFile(
        fileName,
        mimeType,
        initialDirectory,
        bytes,
      );

      if (savedPath == null) return null;
      return Uri.tryParse(savedPath) ?? Uri.file(savedPath);
    } finally {
      // Also when saving fails, so the app does not stay in the picking state.
      await eventSubscription?.cancel();
      onFileSaving?.call(FilePickerStatus.done);
    }
  }

  /// Releases the given Storage Access Framework [uri] grant on Android.
  Future<void> releaseSAFGrant(String uri) async {
    await _api.releaseSafGrant(uri);
  }

  static const _fileTypes = {
    FileType.any: FileTypeMessage.any,
    FileType.custom: FileTypeMessage.custom,
    FileType.image: FileTypeMessage.image,
    FileType.video: FileTypeMessage.video,
    FileType.media: FileTypeMessage.media,
    FileType.audio: FileTypeMessage.audio,
  };

  /// The SAF options of [androidOptions], when they are Android specific.
  static SafOptionsMessage? _safOptions(AndroidOptions androidOptions) {
    if (androidOptions case FilePickerAndroidOptions(:final safOptions)) {
      return SafOptionsMessage(
        grant: switch (safOptions.grant) {
          AndroidSAFGrant.transient => SafGrantMessage.transient,
          AndroidSAFGrant.lifetime => SafGrantMessage.lifetime,
        },
        access: _safAccess(safOptions.accessMode),
        autoPersist: safOptions.persistGrant,
      );
    }
    return null;
  }

  static SafAccessMessage _safAccess(AndroidSAFAccessMode mode) =>
      switch (mode) {
        AndroidSAFAccessMode.readOnly => SafAccessMessage.readOnly,
        AndroidSAFAccessMode.readWrite => SafAccessMessage.readWrite,
      };

  /// The [AndroidPlatformFile] of a picked [file].
  static AndroidPlatformFile _platformFile(PickedFileMessage file) {
    return AndroidPlatformFile.fromMap({
      'path': file.path,
      'name': file.name,
      'size': file.size,
      'identifier': file.identifier,
      if (file.safHandle case final handle?)
        'safHandle': {'uri': handle.uri, 'access': handle.access.name},
    });
  }
}
